"""Static redirects from the retired per-class error pages to the page of each class's code.

Before every error carried a registry code, each ``PipelexError`` class had a generated page at
``errors/<kebab-class-name>/``, which its class-derived type URI named
(``https://docs.pipelex.com/latest/errors/<kebab-class-name>/``). Those pages are retired, and a type URI is now
its code's page. A client that kept an old type URI, or follows one from a stored report, still deserves an
answer rather than a 404, and a non-browser client never runs the site's ``404.html`` script, so the
documentation build holds a static redirect for every retired page: ``mkdocs.yml``'s ``redirect_maps`` sends each
to the page of its class's code, the default of a set or the fallback of a class that takes its cause's code, and
sends a page whose class is gone or abstract to the error codes' index.

The retired pages are a closed historical set, so the keys of the block in ``mkdocs.yml`` are its record; the
targets are derived from the classes, and ``make generate-error-identity`` rewrites them when a class's code
changes. ``tests/unit/pipelex/errors/test_retired_error_page_redirects.py`` fails when they drift.
"""

from __future__ import annotations

import re
from typing import TYPE_CHECKING

from mthds.protocol.problem.registry import CoreCode

from pipelex.errors.error_class_discovery import iter_pipelex_error_subclasses
from pipelex.errors.error_code_declaration import AbstractError, ErrorCodeSet, InheritsCause
from pipelex.tools.misc.string_utils import pascal_case_to_kebab

if TYPE_CHECKING:
    from pipelex.base_exceptions import PipelexError
    from pipelex.errors.error_codes import ErrorCode

BLOCK_BEGIN = "        # BEGIN retired error class pages"
BLOCK_END = "        # END retired error class pages"
ERROR_CODES_INDEX_PAGE = "errors/index.md"
_ENTRY_PATTERN = re.compile(r"^\s+'errors/(?P<kebab>[a-z0-9]+(?:-[a-z0-9]+)*)\.md': '(?P<target>[^']+)'$")
_BLOCK_PREAMBLE: tuple[str, ...] = (
    "        # The retired per-class error pages, each sent to the page of its class's code: the default of a set, the",
    "        # fallback of a class that takes its cause's code, or the error codes' index for a class abstract or gone.",
    "        # The keys are the closed set of retired pages; the targets are generated by `make generate-error-identity`.",
)


class RetiredErrorPagesError(ValueError):
    """``mkdocs.yml`` holds no well-formed block of retired error page redirects."""


def _representative_code(cls: type[PipelexError]) -> ErrorCode | None:
    declaration = cls.error_code
    if isinstance(declaration, ErrorCodeSet):
        return declaration.default
    if isinstance(declaration, InheritsCause):
        return declaration.fallback
    if isinstance(declaration, AbstractError):
        return None
    return declaration


def _code_page_target(code: ErrorCode) -> str:
    if isinstance(code, CoreCode):
        # A core code's page is published with the standard; its type URI is that page.
        return f"https://mthds.ai/errors/{code}"
    return f"errors/{code.replace('.', '/')}.md"


def retired_page_target(*, kebab_name: str, classes_by_kebab: dict[str, type[PipelexError]]) -> str:
    """Where the retired page of the class kebab-cased ``kebab_name`` now redirects.

    Args:
        kebab_name: The retired page's name, the class name kebab-cased.
        classes_by_kebab: The current error classes by their kebab-cased name.

    Returns:
        The page of the class's code (a documentation path for a Pipelex code, the standard's URL for a core
        code), or the error codes' index for a class that is abstract or no longer exists.
    """
    cls = classes_by_kebab.get(kebab_name)
    if cls is None:
        return ERROR_CODES_INDEX_PAGE
    code = _representative_code(cls)
    if code is None:
        return ERROR_CODES_INDEX_PAGE
    return _code_page_target(code)


def _split_block(*, mkdocs_text: str) -> tuple[list[str], list[str], list[str]]:
    lines = mkdocs_text.split("\n")
    try:
        begin = lines.index(BLOCK_BEGIN)
        end = lines.index(BLOCK_END)
    except ValueError as exc:
        msg = f"mkdocs.yml holds no '{BLOCK_BEGIN.strip()}' ... '{BLOCK_END.strip()}' block under redirect_maps."
        raise RetiredErrorPagesError(msg) from exc
    if end < begin:
        msg = "mkdocs.yml's block of retired error page redirects ends before it begins."
        raise RetiredErrorPagesError(msg)
    return lines[: begin + 1], lines[begin + 1 : end], lines[end:]


def retired_page_names(*, mkdocs_text: str) -> list[str]:
    """The retired pages' names, as the block in ``mkdocs.yml`` records them."""
    _head, body, _tail = _split_block(mkdocs_text=mkdocs_text)
    names: list[str] = []
    for line in body:
        if not line.strip() or line.strip().startswith("#"):
            continue
        matched = _ENTRY_PATTERN.match(line)
        if matched is None:
            msg = f"A line of mkdocs.yml's block of retired error page redirects is not a redirect: {line!r}"
            raise RetiredErrorPagesError(msg)
        names.append(matched.group("kebab"))
    return names


def render_retired_error_page_redirects(*, mkdocs_text: str) -> str:
    """``mkdocs.yml`` with the targets of its retired error page redirects derived from the current classes.

    Args:
        mkdocs_text: The current ``mkdocs.yml``.

    Returns:
        The same text, the block between its markers rewritten: the preamble, then one redirect per retired page,
        sorted by name.
    """
    head, _body, tail = _split_block(mkdocs_text=mkdocs_text)
    classes_by_kebab = {pascal_case_to_kebab(cls.__name__): cls for cls in iter_pipelex_error_subclasses()}
    body = list(_BLOCK_PREAMBLE)
    for kebab_name in sorted(set(retired_page_names(mkdocs_text=mkdocs_text))):
        target = retired_page_target(kebab_name=kebab_name, classes_by_kebab=classes_by_kebab)
        body.append(f"        'errors/{kebab_name}.md': '{target}'")
    return "\n".join([*head, *body, *tail])
