"""Command to generate the MTHDS Test Corpus tag vocabulary.

Contract: ``docs/specs/mthds-test-corpus.md`` (workspace root), section "Tag vocabulary".

The generator is unshipped dev tooling — the wheel excludes ``pipelex/cli/dev_cli`` — while the
``vocabulary.toml`` it writes into the corpus tree is committed and ships. That split is the
point: a consumer reads the closed tag set without needing a registry walk, and the tag set
cannot drift from the registry because a unit test regenerates it in memory and compares byte
for byte.
"""

from __future__ import annotations

import re
import sys

from rich.panel import Panel

from pipelex.core.concepts.native.concept_native import NativeConceptCode
from pipelex.runtime_hub import get_console
from pipelex.test_extras.mthds_corpus.vocabulary import vocabulary_path

_ACRONYM_BOUNDARY_RE = re.compile(r"(?<=[A-Z0-9])(?=[A-Z][a-z])")
_WORD_BOUNDARY_RE = re.compile(r"(?<=[a-z0-9])(?=[A-Z])")

_HEADER = """# The MTHDS Test Corpus tag vocabulary — the closed set an entry's `covers` draws from.
#
# GENERATED by `pipelex-dev generate-corpus-vocabulary`. Do not edit this file: the generated
# namespaces are derived from the runtime's own registries, and every exclusion reason is
# declared in the generator's source.
#
# This file ships in the pipelex wheel, so it names a document its readers can reach:
# https://docs.pipelex.com/contribute/mthds-test-corpus/ — which in turn points at the
# cross-repo contract, `docs/specs/mthds-test-corpus.md` in the Pipelex workspace repo.
"""

# A code is excluded when no standalone focused entry could meaningfully exercise it. Exclusions
# are visible decisions, one reason each: an excluded tag stays in the vocabulary and stays usable
# by an entry, it is simply not required to have a focused entry of its own. Keying this map by
# the enum rather than by a string is what stops an exclusion from outliving the code it names —
# an entry reads `NativeConceptCode.PAGE: "…"`, so a code that leaves the registry breaks this
# module at import with an AttributeError naming it, before any generation runs. No code needs
# excluding today; every native concept turned out to support a real focused entry.
_NATIVE_EXCLUSIONS: dict[NativeConceptCode, str] = {}


def normalize_registry_code(*, code: str) -> str:
    """Turn a CamelCase registry code into a snake_case tag local name.

    Insert a separator at every acronym boundary, then at every word boundary, then lowercase.
    The acronym rule is what keeps `JSON` from becoming `j_s_o_n` and splits `JSONSchema` into
    `json_schema`.
    """
    separated = _ACRONYM_BOUNDARY_RE.sub("_", code)
    separated = _WORD_BOUNDARY_RE.sub("_", separated)
    return separated.lower()


def _toml_string(*, value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def _render_native_namespace() -> str:
    blocks: list[str] = []
    for native_code in NativeConceptCode:
        lines = [f"[native.{normalize_registry_code(code=native_code.value)}]", f"code = {_toml_string(value=native_code.value)}"]
        exclusion_reason = _NATIVE_EXCLUSIONS.get(native_code)
        if exclusion_reason is not None:
            lines.append(f"excluded = {_toml_string(value=exclusion_reason)}")
        blocks.append("\n".join(lines))
    return "\n\n".join(blocks)


def generate_corpus_vocabulary_content() -> str:
    """Render the whole vocabulary file, deterministically, in registry declaration order."""
    return f"{_HEADER}\n{_render_native_namespace()}\n"


def generate_corpus_vocabulary_cmd(*, quiet: bool = False) -> None:
    """Write the corpus tag vocabulary into the corpus tree."""
    console = get_console()
    output_path = vocabulary_path()

    if not quiet:
        console.print()
        console.print("[bold]Generating MTHDS Test Corpus vocabulary...[/bold]")
        console.print()

    try:
        content = generate_corpus_vocabulary_content()
    except ValueError as exc:
        if quiet:
            console.print(f"[red]✗ Corpus vocabulary generation: FAILED[/red] - {exc}")
        else:
            console.print(
                Panel(
                    f"[red]✗[/red] Failed to generate the corpus vocabulary\n\n[dim]{exc}[/dim]",
                    title="[bold red]Corpus Vocabulary Generation: FAILED[/bold red]",
                    border_style="red",
                    padding=(1, 2),
                )
            )
            console.print()
        sys.exit(1)

    output_path.write_text(content, encoding="utf-8")

    if quiet:
        console.print("[green]✓ Corpus vocabulary generation: PASSED[/green]")
    else:
        console.print(
            Panel(
                f"[green]✓[/green] Vocabulary generated successfully!\n\n[dim]Output: {output_path}[/dim]",
                title="[bold green]Corpus Vocabulary Generation: PASSED[/bold green]",
                border_style="green",
                padding=(1, 2),
            )
        )
        console.print()
