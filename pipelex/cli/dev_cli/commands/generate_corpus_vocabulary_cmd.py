"""Command to generate the MTHDS Test Corpus tag vocabulary.

Contract: ``docs/specs/mthds-test-corpus.md`` (workspace root), section "Tag vocabulary".

The generator is unshipped dev tooling — the wheel excludes ``pipelex/cli/dev_cli`` — while the
``vocabulary.toml`` it writes into the corpus tree is committed and ships. That split is the
point: a consumer reads the closed tag set without needing a registry walk, and the tag set
cannot drift from the registry because a unit test regenerates it in memory and compares byte
for byte.
"""

from __future__ import annotations

import re
import sys

from rich.markup import escape
from rich.panel import Panel

from pipelex.core.concepts.native.concept_native import NativeConceptCode
from pipelex.pipe_machinery.pipe_blueprint import PipeCategory, PipeType
from pipelex.runtime_hub import get_console
from pipelex.test_extras.mthds_corpus.vocabulary import ValidationLayer, vocabulary_path
from pipelex.validation_error_types import VALIDATION_ERROR_TYPES, PipeFactoryErrorType, PipeValidationErrorType, ValidationErrorType

_ACRONYM_BOUNDARY_RE = re.compile(r"(?<=[A-Z0-9])(?=[A-Z][a-z])")
_WORD_BOUNDARY_RE = re.compile(r"(?<=[a-z0-9])(?=[A-Z])")

_HEADER = """# The MTHDS Test Corpus tag vocabulary — the closed set an entry's `covers` draws from.
#
# GENERATED by `pipelex-dev generate-corpus-vocabulary`. Do not edit this file: `native.*`,
# `operator.*`, `controller.*` and `error.*` are derived from the runtime's own registries,
# `feature.*` is hand-maintained in the generator because no registry describes a language feature,
# and every exclusion reason is declared in the generator's source alongside them.
#
# An `error.*` tag that is not excluded also carries `fails_at`, the earliest layer of checking that
# rejects a bundle carrying the fault: `schema` when a check of the document's shape alone already
# catches it, `runtime` when the document has to be interpreted to notice. A structural consumer
# expects a diagnostic on exactly the `schema` entries and none on the others.
#
# This file ships in the pipelex wheel, so it names a document its readers can reach:
# https://docs.pipelex.com/contribute/mthds-test-corpus/ — which in turn points at the
# cross-repo contract, `docs/specs/mthds-test-corpus.md` in the Pipelex workspace repo.
"""

# A code is excluded when no standalone focused entry could meaningfully exercise it. Exclusions
# are visible decisions, one reason each: an excluded tag stays in the vocabulary and stays usable
# by an entry, it is simply not required to have a focused entry of its own. Keying this map by
# the enum rather than by a string is what stops an exclusion from outliving the code it names —
# an entry reads `NativeConceptCode.PAGE: "…"`, so a code that leaves the registry breaks this
# module at import with an AttributeError naming it, before any generation runs. No code needs
# excluding today; every native concept turned out to support a real focused entry.
_NATIVE_EXCLUSIONS: dict[NativeConceptCode, str] = {}

# The `operator.*` and `controller.*` namespaces come from ONE registry, not two: `PipeType` is the
# closed set of executable pipe kinds, and its `category` property is what splits them. Deriving the
# namespace from that property rather than from a list here is what keeps a newly added pipe kind
# from landing in the wrong half — or in neither.
#
# `PipeSignature` is absent by construction and that is correct: a signature is a contract, not an
# executable kind, so it is deliberately not a `PipeType` member and an explicit `type =
# "PipeSignature"` is rejected upstream. There is nothing for a corpus entry to exercise.
#
# Every registry code here carries the same `Pipe` prefix, and the namespace already says which half
# it is in, so `operator.pipe_llm` would stutter. The prefix is stripped before normalization and
# `code` keeps the registry's own spelling, exactly as `native.yes_no` keeps `code = "YesNo"`.
_PIPE_TYPE_PREFIX = "Pipe"

# `feature.*` is the one hand-maintained namespace: a language feature is a human-named cluster of
# behaviour, not a registry entry. Some span several blueprint fields (optionals show up as `?` in a
# concept spec), some none at all (a multi-file library is a property of the entry *directory*), and
# `pipelex` has no feature registry to walk — so there is nothing to generate from. A tag here
# carries a `description` where a generated one carries `code`, because that sentence is the only
# place the tag's meaning can live.
#
# A tag is added here in the SAME commit that lands its first covering entry, never ahead of it:
# declaring one reds the exhaustivity gate until an entry covers it, and a vocabulary advertising
# coverage the corpus does not have is worse than a short vocabulary. Rendered in alphabetical order,
# there being no registry order to follow.
_FEATURE_TAGS: dict[str, str] = {
    "optionals": (
        "An input declared optional with the `?` suffix, so a run that has no value for it proceeds "
        "instead of failing and the absence is recorded in the working memory. How a method copes with "
        "the absence is the method's business — guarding the reference in a prompt, in a condition "
        "expression, or letting it lift through a chain."
    ),
    "structured_output": (
        "A concept declaring a `structure` table of typed fields, and a pipe producing that shape rather "
        "than free text, so the runtime validates the output against the declared fields."
    ),
    "smart_inputs": (
        "Bare caller values — a string, a number, a dict, a list — interpreted top-down against the entry "
        "pipe's declared signature, so a caller need not wrap each one in its concept envelope."
    ),
    "multi_file_library": (
        "A method split across several `.mthds` files in one directory and merged additively behind a "
        "`bundle.mthds` entry point, so a pipe can be forward-declared as a signature in one file and "
        "satisfied by a concrete definition in another."
    ),
}

# Same contract as `_NATIVE_EXCLUSIONS`, keyed on `PipeType` for the same reason: an exclusion whose
# code leaves the registry breaks this module at import instead of rotting in the generated file.
_PIPE_TYPE_EXCLUSIONS: dict[PipeType, str] = {
    PipeType.PIPE_FUNC: (
        "A PipeFunc names a Python function that is resolved against the runtime's function registry "
        "at validation time, so an entry declaring one fails with \"Function '<name>' not found in "
        'registry" in every consumer that has not registered that exact function. A corpus entry has '
        "to validate everywhere, and the cross-language consumers cannot register a Python function at "
        "all, so no portable focused entry exists. Exercise PipeFunc in a consumer's own fixtures."
    ),
}


# `error.*` is generated from `VALIDATION_ERROR_TYPES`, the closed registry of `error_type` values a
# validation diagnostic can carry. It is the one generated namespace whose registry is already partly
# snake_case: the stage enums spell their codes `missing_input_variable`, the dry-run residual spells
# itself `DryRunError`. `normalize_registry_code` absorbs both with no namespace-local rule — the
# three normalization steps leave an already-snake_case code untouched — and `code` records each
# registry spelling verbatim, exactly as `native.yes_no` records `code = "YesNo"`.
#
# Membership in the registry means a value is *reachable on the wire*, never that a focused entry can
# produce it. A corpus entry is a `.mthds` bundle validated through `validate bundle`, so a type the
# validate path cannot reach is excluded here with the measurement that established it — the runtime's
# truth is not pruned to match the corpus's reach. Keyed on the enums for the same reason the other
# exclusion maps are: a code that leaves the registry breaks this module at import instead of leaving
# a dead exclusion behind in the generated file.
_ERROR_TYPE_EXCLUSIONS: dict[ValidationErrorType, str] = {
    PipeValidationErrorType.CIRCULAR_DEPENDENCY_ERROR: (
        "Raised only from the pipe sorter, and the pipe sorter runs only on `PipelexBundleSpec.to_blueprint()` "
        "— the builder's spec-to-blueprint conversion, which is how an AI-authored spec becomes a bundle. A "
        "`.mthds` file parses straight into a blueprint and never passes through it, so no corpus entry can "
        "produce this. Measured rather than read off the call graph: a self-referencing PipeSequence fails the "
        "dry run with `DryRunError`, and a mutually recursive PipeCondition pair exhausts the interpreter's "
        "stack — neither reports a circular dependency."
    ),
    PipeValidationErrorType.OPTIONAL_FORCE_REDUNDANT: (
        "Advisory-only: it rides the validation report's `warnings` array and never makes a verdict invalid. An "
        "entry contract that models one `expected_error` on an invalid entry has nowhere to put a warning on a "
        "valid one, so there is no shape a focused entry could take. Revisit if the manifest ever grows a "
        "warnings axis."
    ),
    PipeValidationErrorType.UNKNOWN_VALIDATION_ERROR: (
        "The generic fallback for a validation failure that matched no specific code. Reaching it on purpose "
        "would mean authoring a bundle that breaks in a way the categorizer does not recognize — which is a "
        "state to fix in the runtime, not to pin in a corpus entry that would then have to be rewritten the "
        "moment the fault gets a code of its own."
    ),
    PipeFactoryErrorType.UNKNOWN_CONCEPT: (
        "Shadowed: it fires in the pipe factory when a pipe's output names a concept that is neither native, "
        "nor declared in the pipe's own domain, nor domain-qualified — exactly the condition the earlier "
        "concept-reference resolution already rejects, and it reports the same fault as `unresolved_concept`. "
        "Measured across unqualified, cross-domain and qualified-but-missing output refs: every one of them "
        "comes back as `unresolved_concept`, so the factory's own check is unreachable from a `.mthds` file."
    ),
    PipeFactoryErrorType.UNKNOWN_FACTORY_ERROR: (
        "The generic fallback for a pipe-construction failure that matched no specific code, and excluded for "
        "the same reason as its validation counterpart: an entry pinning it would be pinning the absence of a "
        "diagnosis rather than a language fault."
    ),
}


# `fails_at` says, for a fault a corpus entry can produce, which layer of checking rejects it FIRST.
# The two layers are the two ways a `.mthds` document gets read: a JSON-Schema pass over the raw
# document, which sees only shape, and the runtime, which interprets what the shape means. A schema
# check catches a section missing a required key or holding a value outside a closed set; everything
# else — an unresolved reference, an input the flow never supplies, an output whose concept does not
# fit — needs interpretation and belongs to the runtime.
#
# The set below is the `schema` half, and it is short by nature: only a fault visible in the shape
# alone can land in it. Every other non-excluded error type is `runtime`, so this set is the whole
# declaration and there is no second list to keep in step with it. An excluded type gets no
# `fails_at` at all — it has no entry, so there is nothing to have measured, and a value invented for
# one would be an argument dressed as a measurement.
#
# **This is measured, not argued, and CI is what keeps it measured.** The list was established by
# linting every invalid entry against the generated MTHDS JSON Schema: exactly the members below
# produce a diagnostic, every other invalid entry passes. That measurement is then held in place by
# `.pipelex/plxt.toml`, whose corpus exclusions are gated against this set — so the invalid entries
# NOT listed here are linted on every `make plxt-lint` run. Declare a fault `runtime` when the schema
# in fact rejects it and the lint goes red naming the entry; the loop closes without anyone
# remembering to re-measure.
#
# Keyed on the enums for the same reason the exclusion maps are: a code that leaves the registry
# breaks this module at import instead of leaving a stale value behind in the generated file.
_ERROR_TYPE_SCHEMA_FAULTS: frozenset[ValidationErrorType] = frozenset(
    {
        # A `[pipe.x]` section carrying implementation fields but no `type` key, which the schema
        # requires on any pipe that is not a bare signature.
        PipeValidationErrorType.MISSING_PIPE_TYPE,
        # A `type` naming a pipe kind that does not exist, which the schema's closed enum of pipe
        # kinds rejects on sight.
        PipeValidationErrorType.UNKNOWN_PIPE_TYPE,
    }
)


def normalize_registry_code(*, code: str) -> str:
    """Turn a CamelCase registry code into a snake_case tag local name.

    Insert a separator at every acronym boundary, then at every word boundary, then lowercase.
    The acronym rule is what keeps `JSON` from becoming `j_s_o_n` and splits `JSONSchema` into
    `json_schema`.
    """
    separated = _ACRONYM_BOUNDARY_RE.sub("_", code)
    separated = _WORD_BOUNDARY_RE.sub("_", separated)
    return separated.lower()


def _toml_string(*, value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def _render_native_namespace() -> str:
    blocks: list[str] = []
    for native_code in NativeConceptCode:
        lines = [f"[native.{normalize_registry_code(code=native_code.value)}]", f"code = {_toml_string(value=native_code.value)}"]
        exclusion_reason = _NATIVE_EXCLUSIONS.get(native_code)
        if exclusion_reason is not None:
            lines.append(f"excluded = {_toml_string(value=exclusion_reason)}")
        blocks.append("\n".join(lines))
    return "\n\n".join(blocks)


def _render_feature_namespace() -> str:
    blocks: list[str] = []
    for local_name in sorted(_FEATURE_TAGS):
        blocks.append("\n".join([f"[feature.{local_name}]", f"description = {_toml_string(value=_FEATURE_TAGS[local_name])}"]))
    return "\n\n".join(blocks)


def _render_error_namespace() -> str:
    """The `error.*` namespace: every registry code, each either excluded or carrying a `fails_at`.

    The two are mutually exclusive by construction, and a type in both maps is a contradiction rather
    than a precedence question — an exclusion says no entry exists to measure, while a `fails_at`
    claims a measurement was taken on one. Raising routes it through the command's own failure path
    instead of quietly emitting whichever branch happens to come first.
    """
    contradictions = sorted(error_type.value for error_type in _ERROR_TYPE_SCHEMA_FAULTS if error_type in _ERROR_TYPE_EXCLUSIONS)
    if contradictions:
        msg = (
            f"Error types are declared both excluded and schema faults: {', '.join(contradictions)}. "
            "An excluded type has no corpus entry, so no schema measurement exists for it."
        )
        raise ValueError(msg)

    blocks: list[str] = []
    for error_type in VALIDATION_ERROR_TYPES:
        lines = [f"[error.{normalize_registry_code(code=error_type.value)}]", f"code = {_toml_string(value=error_type.value)}"]
        exclusion_reason = _ERROR_TYPE_EXCLUSIONS.get(error_type)
        if exclusion_reason is not None:
            lines.append(f"excluded = {_toml_string(value=exclusion_reason)}")
        else:
            fails_at = ValidationLayer.SCHEMA if error_type in _ERROR_TYPE_SCHEMA_FAULTS else ValidationLayer.RUNTIME
            lines.append(f"fails_at = {_toml_string(value=fails_at)}")
        blocks.append("\n".join(lines))
    return "\n\n".join(blocks)


def _pipe_type_block(*, pipe_type: PipeType, namespace: str) -> str:
    local_name = normalize_registry_code(code=pipe_type.value.removeprefix(_PIPE_TYPE_PREFIX))
    lines = [f"[{namespace}.{local_name}]", f"code = {_toml_string(value=pipe_type.value)}"]
    exclusion_reason = _PIPE_TYPE_EXCLUSIONS.get(pipe_type)
    if exclusion_reason is not None:
        lines.append(f"excluded = {_toml_string(value=exclusion_reason)}")
    return "\n".join(lines)


def _render_pipe_type_namespaces() -> list[str]:
    """The two pipe namespaces, each in registry declaration order, rendered separately.

    One walk of the registry, split by the category the registry itself declares — so a pipe kind
    added tomorrow lands in the right namespace with nothing here to update.
    """
    operators: list[str] = []
    controllers: list[str] = []
    for pipe_type in PipeType:
        # Exhaustive, with no default arm, so the guarantee holds in both directions: a new
        # `PipeType` reds `PipeType.category`'s own match, and a new `PipeCategory` reds this one
        # rather than falling silently into whichever half happened to be the `else`.
        match pipe_type.category:
            case PipeCategory.PIPE_OPERATOR:
                operators.append(_pipe_type_block(pipe_type=pipe_type, namespace="operator"))
            case PipeCategory.PIPE_CONTROLLER:
                controllers.append(_pipe_type_block(pipe_type=pipe_type, namespace="controller"))
    return ["\n\n".join(operators), "\n\n".join(controllers)]


def generate_corpus_vocabulary_content() -> str:
    """Render the whole vocabulary file, deterministically.

    Each generated namespace follows its registry's declaration order, and the two pipe namespaces
    are emitted one after the other rather than interleaved — the file is read by humans choosing an
    entry's `covers`, and grouping should not depend on where a future pipe kind is inserted into
    the enum. `error.*` follows `VALIDATION_ERROR_TYPES`, which is itself ordered by contributing enum
    and then by declaration order, so a new fault shows up as one added block rather than a reshuffle.
    `feature.*` has no registry to follow, so it renders alphabetically; it goes last because it is
    the one namespace a reader cannot predict from a registry.
    """
    namespaces = [_render_native_namespace(), *_render_pipe_type_namespaces(), _render_error_namespace(), _render_feature_namespace()]
    return f"{_HEADER}\n" + "\n\n".join(namespaces) + "\n"


def generate_corpus_vocabulary_cmd(*, quiet: bool = False) -> None:
    """Write the corpus tag vocabulary into the corpus tree."""
    console = get_console()
    output_path = vocabulary_path()

    if not quiet:
        console.print()
        console.print("[bold]Generating MTHDS Test Corpus vocabulary...[/bold]")
        console.print()

    try:
        content = generate_corpus_vocabulary_content()
    except ValueError as exc:
        if quiet:
            console.print(f"[red]✗ Corpus vocabulary generation: FAILED[/red] - {escape(str(exc))}")
        else:
            console.print(
                Panel(
                    f"[red]✗[/red] Failed to generate the corpus vocabulary\n\n[dim]{escape(str(exc))}[/dim]",
                    title="[bold red]Corpus Vocabulary Generation: FAILED[/bold red]",
                    border_style="red",
                    padding=(1, 2),
                )
            )
            console.print()
        sys.exit(1)

    output_path.write_text(content, encoding="utf-8")

    if quiet:
        console.print("[green]✓ Corpus vocabulary generation: PASSED[/green]")
    else:
        console.print(
            Panel(
                f"[green]✓[/green] Vocabulary generated successfully!\n\n[dim]Output: {escape(str(output_path))}[/dim]",
                title="[bold green]Corpus Vocabulary Generation: PASSED[/bold green]",
                border_style="green",
                padding=(1, 2),
            )
        )
        console.print()
