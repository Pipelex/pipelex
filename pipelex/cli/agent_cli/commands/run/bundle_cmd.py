from pipelex.cli.commands.run._run_output_folder import RUN_RESULTS_DIR_NAME
from pipelex.hosted.exceptions import HostedRunSourceError
from pipelex.hosted.hosted_run import HostedRunRequest
from pipelex.hosted.run_config import RunExecution  # ruff: ignore[typing-only-first-party-import] - typer reads the --runner annotation at runtime
from pipelex.mthds_parsing.helpers import is_pipelex_file
from pipelex.mthds_parsing.parser import MthdsParser, decode_mthds_text
from pipelex.pipe_operators.exceptions import PipeOperatorModelAvailabilityError
from pipelex.pipelex import Pipelex
from pipelex.pipeline.exceptions import MethodEntryError, PipelineExecutionError, ValidateBundleError
from pipelex.pipeline.validate_bundle_translation import translate_to_validate_bundle_error

if TYPE_CHECKING:
    from mthds.method_tree.models import MethodTree


def run_bundle_cmd(
    path: Annotated[
        str,
        typer.Argument(help="Path to a .mthds bundle file, or a method's folder, which starts at its entry pipe unless --pipe names one"),
    ],
    pipe: Annotated[
        str | None,
        typer.Option("--pipe", help="Pipe code to run (overrides bundle's main_pipe)"),
    ] = None,
    inputs: Annotated[
        str | None,
        typer.Option("--inputs", "-i", help="Inputs: a JSON or TOML file (by its extension), or inline JSON starting with {"),
    ] = None,
    dry_run: Annotated[
        bool,
        typer.Option("--dry-run", help="Run pipeline in dry mode (no actual inference calls)"),
    ] = False,
    mock_inputs: Annotated[
        bool,
        typer.Option("--mock-inputs", help="Generate mock data for missing required inputs (requires --dry-run)"),
    ] = False,
    graph: Annotated[
        bool,
        typer.Option("--graph/--no-graph", help="Generate execution graph visualizations (saved alongside output)"),
    ] = True,
    costs: Annotated[
        bool,
        typer.Option("--costs/--no-costs", help="Emit usage (cost) tracing events. Default on."),
    ] = True,
    library_dir: Annotated[
        list[str] | None,
        typer.Option("--library-dir", "-L", help="Directory to search for pipe definitions (.mthds files)"),
    ] = None,
    with_memory: Annotated[
        bool,
        typer.Option("--with-memory", help="Include full working memory in output (for piping to another method)"),
    ] = False,
    output_format: Annotated[
        CliOutputFormat,
        typer.Option("--format", help="Success output format: markdown (default) or json (structured)"),
    ] = CliOutputFormat.MARKDOWN,
    error_format: Annotated[
        CliOutputFormat | None,
        typer.Option("--error-format", help="Error output format: markdown or json (defaults to the program's --error-format, then to --format)"),
    ] = None,
    runner: Annotated[
        RunExecution | None,
        typer.Option("--runner", help=RUNNER_OPTION_HELP),
    ] = None,
    hosted: Annotated[
        bool | None,
        typer.Option("--hosted/--local", help=HOSTED_OPTION_HELP),
    ] = None,
    base_url: Annotated[
        str | None,
        typer.Option("--base-url", help=BASE_URL_OPTION_HELP),
    ] = None,
) -> None:
    """Execute a pipeline from a bundle file (.mthds) or pipeline directory.

    Default output is markdown; use --format json for structured JSON.
    Results go to stdout on success, errors to stderr with exit code 1.
    Graph visualizations are generated by default; use --no-graph to disable.

    Examples:
        pipelex-agent run bundle mthds-wip/pipeline_01/
        pipelex-agent run bundle my_bundle.mthds --pipe my_pipe
        pipelex-agent run bundle pipeline_01/ --dry-run --mock-inputs
        pipelex-agent run bundle pipeline_01/ --format json
        pipelex-agent run bundle pipeline_01/ --runner hosted
    """
    use_agent_cli_error_format(error_format=error_format, output_format=output_format)

    # Validate --mock-inputs requires --dry-run
    if mock_inputs and not dry_run:
        agent_argument_error("--mock-inputs requires --dry-run", argument="--mock-inputs", reason="requires --dry-run")

    pipe_code: str | None = pipe
    bundle_path: str | None = None
    auto_inputs_dir: Path | None = None
    target_path = Path(path)

    # The method tree the run reads, whose digest the run records: the folder's, or the bundle file's own.
    method_tree: MethodTree | None = None
    # Where a folder run that named its pipe writes its output folders: `results/` in the folder, which has no entry
    # bundle to write beside.
    output_dir_override: Path | None = None
    # The pipe a hosted run names: `--pipe`, else the main pipe the local run starts at, qualified by its domain, so the
    # hosted API starts at the same pipe when two domains of the files it is sent define the same code.
    hosted_pipe_code: str | None = pipe
    if target_path.is_dir():
        # Directory mode: the method rooted at or above the folder, started where the protocol's rule says
        try:
            folder_run = resolve_method_folder_run(directory=target_path, pipe_override=pipe)
        except ValidateBundleError as exc:
            agent_error(exc.message, cause=exc)
        except MethodEntryError as exc:
            # No pipe to start at is the run's refusal and no verdict: its problem carries its own code.
            agent_error(exc.message, cause=exc)
        except PipelexConfigError as exc:
            # Listing the tree reads its limits from the configuration, before the boot would.
            report_agent_init_failure(error=exc)
        method_tree = folder_run.tree
        pipe_code = folder_run.pipe_code
        if folder_run.entry is not None and folder_run.entry_bundle_file is not None:
            bundle_path = str(folder_run.entry_bundle_file)
            hosted_pipe_code = folder_run.entry.pipe_ref
        else:
            output_dir_override = target_path / RUN_RESULTS_DIR_NAME

        # Hand the directory to parse_cli_inputs as the lowest-priority inputs source: it probes
        # for inputs.json / inputs.toml (and applies the ambiguity rule) only after --inputs and
        # stdin are ruled out, so an ambiguous dir can't pre-empt an explicit flag or piped stdin.
        auto_inputs_dir = target_path

        # Add directory as library dir (prepend to user-supplied list)
        target_dir_str = str(target_path)
        if library_dir is None:
            library_dir = [target_dir_str]
        elif target_dir_str not in library_dir:
            library_dir = [target_dir_str, *library_dir]

    elif is_pipelex_file(target_path):
        bundle_path = path
    else:
        agent_argument_error(
            f"'{path}' is not a .mthds file or directory. Use 'run pipe <code>' for pipe codes, or 'run bundle <path>' for .mthds files/directories.",
            argument=path,
            reason="not a .mthds file or a directory",
        )

    # Load MTHDS content from bundle
    mthds_content: str | None = None
    if bundle_path:
        # The file is read before its tree is listed: one this machine would not let the command read is the file it
        # was handed (`client.file_unreadable`), never a fault of the method.
        try:
            mthds_bytes = Path(bundle_path).read_bytes()
        except FileNotFoundError as exc:
            agent_file_error(f"Bundle file not found: {bundle_path}", path=bundle_path, reason="not found", cause=exc)
        except OSError as exc:
            agent_unreadable_file_error(error=exc, path=bundle_path)
        if method_tree is None:
            # The bundle file named alone: its own tree, which a folder run has already listed.
            try:
                method_tree = list_bundle_file_tree(bundle_file=target_path)
            except ValidateBundleError as exc:
                agent_error(exc.message, cause=exc)
            except PipelexConfigError as exc:
                # Listing the tree reads its limits from the configuration, before the boot would.
                report_agent_init_failure(error=exc)
        try:
            # A file that is not UTF-8 text does not parse: the invalid verdict `validate` gives it, `method.syntax`.
            with translate_to_validate_bundle_error():
                mthds_content = decode_mthds_text(content=mthds_bytes, source=bundle_path)
            if not pipe_code:
                # A bundle file named alone starts at its own main_pipe.
                # A bundle that does not parse is the invalid verdict, with the items `validate` gives,
                # as it is when the run refuses it while loading.
                with translate_to_validate_bundle_error():
                    bundle_blueprint = MthdsParser.make_pipelex_bundle_blueprint(mthds_content=mthds_content, mthds_source=bundle_path)
                main_pipe_code = bundle_blueprint.main_pipe
                if not main_pipe_code:
                    agent_error(
                        f"Bundle '{bundle_path}' does not declare a main_pipe. Specify a pipe code with --pipe.",
                        code=CoreCode.REQUEST_PIPE_UNSPECIFIED,
                        params={"candidates": sorted(bundle_blueprint.pipe or {})},
                    )
                pipe_code = main_pipe_code
                hosted_pipe_code = main_pipe_code
        except ValidateBundleError as exc:
            agent_error(f"Failed to parse bundle '{bundle_path}': {exc.message}", cause=exc)

    # Load inputs: --inputs flag takes priority, then stdin fallback, then auto-detected
    parsed_inputs = parse_cli_inputs(inputs_arg=inputs, stdin_fallback=True, auto_inputs_dir=auto_inputs_dir)
    pipeline_inputs: dict[str, Any] | None = parsed_inputs.pipeline_inputs

    execution = resolve_agent_run_execution(runner=runner, hosted=hosted, base_url=base_url)
    if execution.is_hosted:
        refuse_local_only_flags(dry_run=dry_run, mock_inputs=mock_inputs)
        # The bundle goes first, then the rest of the library a local run would load with it: -L, else PIPELEXPATH.
        try:
            bundle_files = collect_mthds_files(
                primary=Path(bundle_path) if bundle_path else None, library_dirs=hosted_library_dirs(library_dirs=library_dir)
            )
        except HostedRunSourceError as exc:
            agent_error(exc.message, cause=exc)
        request = HostedRunRequest(
            mthds_files=bundle_files,
            pipe_code=hosted_pipe_code,
            inputs=pipeline_inputs,
            inputs_base_dir=parsed_inputs.inputs_base_dir,
        )
        run_hosted_for_agent(request=request, base_url=base_url, with_memory=with_memory, output_format=output_format)
        return

    make_pipelex_for_agent_cli(needs_inference=not dry_run)

    try:
        result = asyncio.run(
            run_pipeline_core(
                pipe_code=pipe_code,  # type: ignore[arg-type]
                mthds_contents=[mthds_content] if mthds_content else None,
                bundle_uris=[bundle_path] if bundle_path else None,
                inputs=pipeline_inputs,
                dry_run=dry_run,
                mock_inputs=mock_inputs,
                library_dirs=library_dir,
                graph=graph,
                costs=costs,
                with_memory=with_memory,
                inputs_base_dir=parsed_inputs.inputs_base_dir,
                output_dir_override=output_dir_override,
                method_tree=method_tree,
            )
        )
        agent_success_formatted(
            result, markdown_renderer=functools.partial(format_run_markdown, with_memory=with_memory), output_format=output_format
        )

    except PipelineExecutionError as exc:
        agent_error(exc.message, cause=exc)

    except PipeOperatorModelAvailabilityError as exc:
        availability_extra: dict[str, Any] = {
            "pipe_code": exc.pipe_code,
            "model_handle": exc.model_handle,
        }
        if exc.fallback_list:
            availability_extra["fallback_list"] = exc.fallback_list
        if exc.pipe_stack:
            availability_extra["pipe_stack"] = exc.pipe_stack
        agent_error(exc.message, cause=exc, **availability_extra)

    except Exception as exc:  # ruff: ignore[blind-except]
        # Agent CLI command boundary: agent_error() (NoReturn) converts any unexpected failure into its problem.
        agent_error(str(exc), cause=exc)

    finally:
        Pipelex.teardown_if_needed()
