"""ts-zod emitter: project a crate's concept set as a pure TypeScript + Zod types file plus a binder.

`types.ts` imports **only** `zod` — Zod schemas plus their inferred types — so it stays dependency-free
and portable. `binder.ts` is the thin companion that exposes a typed `parse<Name>` / `serialize<Name>`
pair per concept over those schemas. A pipe's IO types are concepts, so a pipe's output parser / input
serializer is just the binder pair for those concept types — the binder is the concept-set-wide
realization of the per-pipe parse/serialize helpers.

**Wire-native field keys (D10).** Object keys are the crate's snake_case field names *verbatim*, so a
schema validates a wire payload directly — no key remapping layer, and therefore no way to silently
corrupt arbitrary keys inside a `z.record()` / `z.unknown()` value (a camelCase remapping binder can't
tell a schema-declared field key from arbitrary data — e.g. `native.JSON`'s `json_obj` map). The
inferred `z.infer` types therefore carry snake_case keys. (This departs from a camelCase-TS convention;
if camelCase ergonomics are later wanted they must ride a *schema-aware* transform, not a blind deep
key remap.) Concept references use `z.lazy(() => XSchema)` so schema
declaration order is irrelevant and reference cycles are handled.

TypeScript customization is by declaration merging (augment the generated `interface`/module from a
sibling file), the TS analog of the Python subclassing story; the generated files are never edited.
"""

import json
import re
from typing import Any, cast

from pipelex.codegen.emitters.naming import allocate_ts_type_names
from pipelex.codegen.emitters.target import EmittedFile
from pipelex.codegen.resolved_concepts import ResolvedConcept, ResolvedLibrary
from pipelex.core.concepts.resolved_fields import ResolvedField, ResolvedType, ResolvedTypeKind, iter_imprecision_reasons
from pipelex.tools.misc.json_utils import clean_json_content

_FILENAME = "types.ts"
_BINDER_FILENAME = "binder.ts"

# Prettier's default `printWidth`. The emitted files must be prettier-clean on arrival, or a consumer's
# formatter run rewrites the bytes and invalidates the codegen stamp (`pipelex codegen check` would then
# report the file as hand-edited). Two prettier behaviors drive the emitted shape: it collapses runs of
# blank lines to a single one, and it keeps an import on one line while it fits within this width.
TS_PRINT_WIDTH = 80


def emit_ts_zod(library: ResolvedLibrary) -> list[EmittedFile]:
    """Emit the pure `types.ts` file and its `binder.ts` companion (wire<->domain parse/serialize)."""
    concepts = sorted(library.concepts, key=lambda concept: concept.concept_ref)
    by_ref = library.by_ref()
    type_name_by_ref = allocate_ts_type_names(library)
    recursive_refs = _find_recursive_concept_refs(concepts)
    header = _ts_header()
    blocks = [_render_schema(concept, by_ref=by_ref, type_name_by_ref=type_name_by_ref, recursive_refs=recursive_refs) for concept in concepts]
    if blocks:
        body = f'{header}import {{ z }} from "zod";\n\n' + "\n\n".join(blocks) + "\n"
    else:
        # Nothing to project: the header alone. Keeping the import would leave `z` unused above a trailing
        # blank-line run prettier collapses — a reformat, and a broken stamp. See `_emit_binder`.
        body = header
    return [EmittedFile(filename=_FILENAME, content=body), _emit_binder(concepts, type_name_by_ref=type_name_by_ref)]


def _ts_header() -> str:
    return (
        "// ---------------------------------------------------------------------------\n"
        "// AUTOGENERATED by Pipelex codegen — DO NOT EDIT.\n"
        "//\n"
        "// This file is a projection of a normalized MTHDS library crate. It is\n"
        "// regenerated from the method; any hand edit here is overwritten.\n"
        "//\n"
        "// To customize a generated type, do NOT edit this file. Augment it from a\n"
        "// sibling module via declaration merging — augmentations survive regeneration.\n"
        "//\n"
        "// projection: types / ts-zod\n"
        "// ---------------------------------------------------------------------------\n"
    )


def _render_schema(
    concept: ResolvedConcept,
    *,
    by_ref: dict[str, ResolvedConcept],
    type_name_by_ref: dict[str, str],
    recursive_refs: set[str],
) -> str:
    type_name = type_name_by_ref[concept.concept_ref]
    doc = _jsdoc(concept.description, imprecise=concept.imprecision_reason if concept.structureless else None)

    schema_expr = _schema_expr(concept, by_ref=by_ref, type_name_by_ref=type_name_by_ref)
    if concept.concept_ref in recursive_refs:
        type_expr = _concept_type_expr(concept, by_ref=by_ref, type_name_by_ref=type_name_by_ref)
        return f"{doc}export type {type_name} = {type_expr};\nexport const {type_name}Schema: z.ZodType<{type_name}> = {schema_expr};"

    # A long enough concept name pushes the alias past prettier's print width, and prettier then breaks
    # the generic — rewriting the bytes and invalidating the stamp. Emit the broken form ourselves.
    alias = f"export type {type_name} = z.infer<typeof {type_name}Schema>;"
    if len(alias) > TS_PRINT_WIDTH:
        alias = f"export type {type_name} = z.infer<\n  typeof {type_name}Schema\n>;"
    return f"{doc}export const {type_name}Schema = {schema_expr};\n{alias}"


def _schema_expr(
    concept: ResolvedConcept,
    *,
    by_ref: dict[str, ResolvedConcept],
    type_name_by_ref: dict[str, str],
) -> str:
    if concept.base_ref is not None and not concept.fields:
        base = by_ref.get(concept.base_ref)
        if base is not None:
            base_name = type_name_by_ref[base.concept_ref]
            return f"z.lazy(() => {base_name}Schema)"
        return "z.unknown()"
    if not concept.fields:
        if concept.structureless:
            # Structureless / opaque concept: unknown shape, surfaced (never guessed).
            return "z.unknown()"
        return "z.object({})"
    field_lines = "\n".join(_render_field(concept_field, by_ref=by_ref, type_name_by_ref=type_name_by_ref) for concept_field in concept.fields)
    return f"z.object({{\n{field_lines}\n}})"


def _render_field(
    concept_field: ResolvedField,
    *,
    by_ref: dict[str, ResolvedConcept],
    type_name_by_ref: dict[str, str],
) -> str:
    # Wire-native key: the crate's snake_case field name verbatim (D10), so the schema validates the
    # wire payload directly and no key transform can corrupt nested record/opaque data.
    key = concept_field.name
    reasons = list(dict.fromkeys(iter_imprecision_reasons(concept_field.resolved_type)))
    doc = _jsdoc(concept_field.description, imprecise="; ".join(reasons) if reasons else None, indent="  ")
    expr = _zod_type(concept_field.resolved_type, by_ref=by_ref, type_name_by_ref=type_name_by_ref)
    modifiers = _presence_modifiers(concept_field)

    flat = f"  {key}: {expr}{''.join(modifiers)},"
    if len(flat) <= TS_PRINT_WIDTH or "\n" in expr:
        return f"{doc}{flat}"
    return f"{doc}  {key}: {_break_zod_expr(expr, modifiers=modifiers)},"


def _presence_modifiers(concept_field: ResolvedField) -> list[str]:
    """The zod member calls that encode a field's presence, in chain order.

    Both non-required spellings are **null-tolerant**, because the runtime serializes an unset optional
    field as an explicit `null`: the generated runtime class annotates every non-required field `X | None`
    and `dump_for_transport()` keeps nulls on purpose (no `exclude_none`). `.optional()` means
    `T | undefined` in zod and rejects that payload, so a schema that spelled it would fail to parse the
    very wire the engine produces. The wire genuinely carries both spellings of "unset" — a key a partial
    payload omitted, and a key the runtime nulled — and `.nullish()` is the honest description of that.

    A defaulted field is non-required by construction (the blueprint validator refuses `required = true`
    beside a `default_value`, E3), and a producer may set it to `None` explicitly, so `.default(...)` needs
    `.nullable()` in front of it for the same reason.
    """
    if concept_field.default_value is not None:
        return [".nullable()", f".default({_format_default_value(concept_field.default_value)})"]
    if not concept_field.required:
        return [".nullish()"]
    return []


def _break_zod_expr(expr: str, *, modifiers: list[str]) -> str:
    """Prettier's rendering of a field expression too long to sit on one line.

    Prettier picks between two shapes by how many calls the chain carries, and the count is what decides —
    not which expression it is. **Two or more** calls (every field carrying a presence modifier, and
    `z.number().int()` on its own) and it breaks the whole member chain: `z` stays on the property line and
    every call goes onto a line of its own. A **single** call has no chain to break, so prettier explodes
    that call's arguments in place instead.

    Both unbounded widths reach this. A `z.enum([...])`'s members are authored choices with no length bound,
    and the *field name* and *default literal* are authored too — so an ordinary `z.string()` carrying a
    default overflows on nothing but a long name, which is why the break cannot key on the expression.

    The one shape still unmodelled is a single call whose arguments must explode for a reason other than
    enum members — a `z.lazy(() => AVeryLongConceptNameSchema)` on a required field. It stays flat, and
    `test_emitted_ts_lines_fit_the_print_width` is the guard that turns that into a failing test rather
    than a silently broken stamp.
    """
    head, *calls = _split_member_chain(expr)
    chain = calls + modifiers
    if len(chain) < 2:
        # No chain to break: prettier explodes the single call's arguments, and only `z.enum` is modelled.
        if chain and _is_enum_call(chain[0]):
            return f"{head}{_explode_enum_call(chain[0], indent=2)}"
        return f"{expr}{''.join(modifiers)}"
    rendered = "".join(f"\n    {_render_broken_call(call, indent=4)}" for call in chain)
    return f"{head}{rendered}"


def _render_broken_call(call: str, *, indent: int) -> str:
    """One member call on its own line after the chain break, exploded only if it still overflows there.

    Prettier re-measures every call once the chain is broken, and one that now fits is left flat — the
    threshold is exact, `indent + len(call) <= TS_PRINT_WIDTH` stays on the line. Exploding unconditionally
    is what a `z.enum` special case looks like from the other side: an ordinary three-choice enum carrying a
    default reaches this branch on its `.nullable()` width alone, sits far inside the width at indent 4, and
    was being exploded into a shape prettier immediately folds back — a consumer's first format run changes
    the bytes and `pipelex codegen check` reports an untouched artifact as hand-edited. Only the enum's
    arguments are modelled here, for the same reason as in the single-call branch.
    """
    if _is_enum_call(call) and indent + len(call) > TS_PRINT_WIDTH:
        return _explode_enum_call(call, indent=indent)
    return call


def _split_member_chain(expr: str) -> list[str]:
    """Split `z.record(z.string(), z.number()).int()` into its head and calls: `["z", ".record(…)", ".int()"]`.

    Splits on the dots sitting at bracket depth zero **outside a string literal**, and the literal half is
    what makes the count trustworthy. A choice is authored prose whose brackets need not balance — `a)` is
    an ordinary answer option — so counting the brackets *inside* one walks the depth to zero mid-literal
    and cuts the chain through the middle of a string. Both quote styles have to be walked, because
    `_ts_string` spells a choice carrying a `"` single-quoted.
    """
    parts: list[str] = []
    depth = 0
    current = ""
    quote: str | None = None
    escaped = False
    for char in expr:
        if escaped:
            escaped = False
        elif quote is not None:
            if char == "\\":
                escaped = True
            elif char == quote:
                quote = None
        elif char in {'"', "'"}:
            quote = char
        else:
            if char == "." and depth == 0 and current:
                parts.append(current)
                current = ""
            depth += {"(": 1, "[": 1, "{": 1, ")": -1, "]": -1, "}": -1}.get(char, 0)
        current += char
    parts.append(current)
    return parts


def _is_enum_call(call: str) -> bool:
    """Whether a member call is the one shape whose arguments can overflow on their own contents."""
    return call.startswith(".enum([") and call.endswith("])")


def _explode_enum_call(call: str, *, indent: int) -> str:
    """Render `.enum([...])` with one choice per line, for a call sitting at column `indent`.

    The split has to walk the string literals rather than `str.split(",")`: a choice is authored text, and
    an ordinary one like `"yes, absolutely"` carries a comma. Split naively it became two unterminated
    literals — generated TypeScript that does not parse, on any crate whose choice list overflows. It walks
    both quote styles, since `_ts_string` spells a choice carrying a `"` single-quoted.
    """
    rendered = "".join(f"{' ' * (indent + 2)}{member},\n" for member in _split_enum_members(call[len(".enum([") : -2]))
    return f".enum([\n{rendered}{' ' * indent}])"


def _split_enum_members(members_text: str) -> list[str]:
    """Split `"a", 'b, c'` on its separating commas only — the ones outside a string literal.

    Both quote styles have to be walked, not just the double one: `_ts_string` spells a choice carrying a
    `"` single-quoted, since that is the style prettier keeps. Track only `"` and an ordinary authored
    choice like `'say "hi", then continue'` is cut at its own comma into two unterminated literals.
    """
    members: list[str] = []
    current = ""
    quote: str | None = None
    escaped = False
    for char in members_text:
        if escaped:
            escaped = False
        elif quote is not None:
            if char == "\\":
                escaped = True
            elif char == quote:
                quote = None
        elif char in {'"', "'"}:
            quote = char
        elif char == ",":
            members.append(current.strip())
            current = ""
            continue
        current += char
    members.append(current.strip())
    return members


def _format_default_value(value: Any) -> str:
    """Render a JSON-safe default as a canonical *TypeScript* literal, not a JSON one.

    Keys are sorted so mapping insertion order cannot affect the output. Beyond that the two spellings
    diverge on objects, and JSON's is the one prettier rewrites: it pads the braces (`{ a: 1 }`) and drops
    the quotes from every key that is a valid identifier, at any line width. Emitting JSON therefore made a
    single dict-valued default enough to have a consumer's formatter change the bytes and `pipelex codegen
    check` report an untouched artifact as hand-edited. Scalars and arrays are spelled the same in both.
    """
    return _ts_literal(clean_json_content(value))


# A key prettier is willing to leave unquoted in an object literal: a plain JS identifier.
_TS_IDENTIFIER = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")


def _ts_string(text: str) -> str:
    """A string literal in the quote style prettier would leave alone — the same rule ruff applies to Python.

    Double quotes by default, single only where that **strictly reduces** the escape count. `json.dumps`
    always double-quotes, so a choice or default carrying a `"` came out double-quoted with both quotes
    escaped, which prettier rewrites to the escape-free `'say "hi"'` on a consumer's first format run,
    reporting the artifact as hand-edited.
    """
    quote = "'" if text.count("'") < text.count('"') else '"'
    body = json.dumps(text)[1:-1].replace('\\"', '"').replace(quote, f"\\{quote}")
    return f"{quote}{body}{quote}"


def _ts_literal(value: Any) -> str:
    """One JSON-safe value as the TypeScript literal prettier would leave alone."""
    if isinstance(value, str):
        return _ts_string(value)
    if isinstance(value, dict):
        pairs = cast("dict[str, Any]", value)
        if not pairs:
            return "{}"
        rendered = ", ".join(f"{_ts_object_key(key)}: {_ts_literal(pairs[key])}" for key in sorted(pairs))
        return f"{{ {rendered} }}"
    if isinstance(value, list):
        items = cast("list[Any]", value)
        return f"[{', '.join(_ts_literal(item) for item in items)}]"
    return json.dumps(value)


def _ts_object_key(key: Any) -> str:
    """An object-literal key, quoted only where prettier keeps the quotes (a non-identifier key).

    A quoted key goes through `_ts_string` like any other literal, not through `json.dumps`: prettier
    applies the same fewer-escapes quote rule to a key as to a value, so a key carrying a `"` — legal TOML
    on a `type = "dict"` field, `default_value = { 'marked "urgent"' = 3 }` — came out double-quoted with
    escapes and was rewritten to `'marked "urgent"'` on the consumer's first format run.

    A non-string key is stringified first, exactly as `json.dumps` used to coerce one — `default_value` is
    typed `Any`, so nothing but authoring convention keeps a non-string out, and a crash here would be a
    worse answer than the spelling the emitter has always produced.
    """
    text = key if isinstance(key, str) else json.dumps(key)
    return text if _TS_IDENTIFIER.match(text) else _ts_string(text)


def _concept_type_expr(
    concept: ResolvedConcept,
    *,
    by_ref: dict[str, ResolvedConcept],
    type_name_by_ref: dict[str, str],
) -> str:
    """Render the explicit TypeScript type required to break recursive schema inference."""
    if concept.base_ref is not None and not concept.fields:
        base = by_ref.get(concept.base_ref)
        return type_name_by_ref[base.concept_ref] if base is not None else "unknown"
    if concept.structureless:
        return "unknown"
    field_lines = "\n".join(_render_type_field(field, by_ref=by_ref, type_name_by_ref=type_name_by_ref) for field in concept.fields)
    return f"{{\n{field_lines}\n}}"


def _render_type_field(
    concept_field: ResolvedField,
    *,
    by_ref: dict[str, ResolvedConcept],
    type_name_by_ref: dict[str, str],
) -> str:
    type_expr = _ts_type(concept_field.resolved_type, by_ref=by_ref, type_name_by_ref=type_name_by_ref)
    # Mirror `_presence_modifiers` branch for branch: this declared type is what the annotated
    # `z.ZodType<Name>` is checked against, so it has to be exactly the schema's inferred output —
    # `.nullable().default(…)` infers `T | null`, `.nullish()` infers `T | null | undefined`.
    if concept_field.default_value is not None:
        return f"  {concept_field.name}: {type_expr} | null;"
    if not concept_field.required:
        return f"  {concept_field.name}?: {type_expr} | null;"
    return f"  {concept_field.name}: {type_expr};"


def _ts_type(
    resolved_type: ResolvedType,
    *,
    by_ref: dict[str, ResolvedConcept],
    type_name_by_ref: dict[str, str],
) -> str:
    """Render one neutral resolved type as an explicit TypeScript type expression."""
    match resolved_type.kind:
        case ResolvedTypeKind.TEXT | ResolvedTypeKind.DATE | ResolvedTypeKind.DATETIME | ResolvedTypeKind.TIME:
            return "string"
        case ResolvedTypeKind.NUMBER | ResolvedTypeKind.INTEGER:
            return "number"
        case ResolvedTypeKind.BOOLEAN:
            return "boolean"
        case ResolvedTypeKind.LITERAL:
            return " | ".join(_ts_string(choice) for choice in resolved_type.choices or [])
        case ResolvedTypeKind.CONCEPT:
            return _concept_type(resolved_type, by_ref=by_ref, type_name_by_ref=type_name_by_ref)
        case ResolvedTypeKind.LIST:
            item = _ts_type(resolved_type.item, by_ref=by_ref, type_name_by_ref=type_name_by_ref) if resolved_type.item else "unknown"
            return f"Array<{item}>"
        case ResolvedTypeKind.DICT:
            value = _ts_type(resolved_type.value, by_ref=by_ref, type_name_by_ref=type_name_by_ref) if resolved_type.value else "unknown"
            return f"Record<string, {value}>"
        case ResolvedTypeKind.ANY:
            return "unknown"


def _concept_type(
    resolved_type: ResolvedType,
    *,
    by_ref: dict[str, ResolvedConcept],
    type_name_by_ref: dict[str, str],
) -> str:
    concept_ref = resolved_type.concept_ref
    if concept_ref is None:
        return "unknown"
    concept = by_ref.get(concept_ref)
    return type_name_by_ref[concept.concept_ref] if concept is not None else "unknown"


def _find_recursive_concept_refs(concepts: list[ResolvedConcept]) -> set[str]:
    """Find concepts that can reach themselves through an in-crate type reference."""
    graph = {concept.concept_ref: _concept_dependencies(concept) for concept in concepts}
    recursive_refs: set[str] = set()
    for origin_ref, dependencies in graph.items():
        pending_refs = list(dependencies)
        visited_refs: set[str] = set()
        while pending_refs:
            current_ref = pending_refs.pop()
            if current_ref == origin_ref:
                recursive_refs.add(origin_ref)
                break
            if current_ref in visited_refs:
                continue
            visited_refs.add(current_ref)
            pending_refs.extend(graph.get(current_ref, set()))
    return recursive_refs


def _concept_dependencies(concept: ResolvedConcept) -> set[str]:
    dependencies: set[str] = {concept.base_ref} if concept.base_ref is not None else set()
    for concept_field in concept.fields:
        dependencies.update(_resolved_type_concept_refs(concept_field.resolved_type))
    return dependencies


def _resolved_type_concept_refs(resolved_type: ResolvedType) -> set[str]:
    concept_refs: set[str] = {resolved_type.concept_ref} if resolved_type.concept_ref is not None else set()
    for child_type in (resolved_type.item, resolved_type.key, resolved_type.value):
        if child_type is not None:
            concept_refs.update(_resolved_type_concept_refs(child_type))
    return concept_refs


def _zod_type(
    resolved_type: ResolvedType,
    *,
    by_ref: dict[str, ResolvedConcept],
    type_name_by_ref: dict[str, str],
) -> str:
    match resolved_type.kind:
        case ResolvedTypeKind.TEXT:
            return "z.string()"
        case ResolvedTypeKind.NUMBER:
            return "z.number()"
        case ResolvedTypeKind.INTEGER:
            return "z.number().int()"
        case ResolvedTypeKind.BOOLEAN:
            return "z.boolean()"
        case ResolvedTypeKind.DATE | ResolvedTypeKind.DATETIME | ResolvedTypeKind.TIME:
            # ISO date / datetime / time string on the wire (the `@wire` field keeps the shape documented).
            return "z.string()"
        case ResolvedTypeKind.LITERAL:
            choices = ", ".join(_ts_string(choice) for choice in resolved_type.choices or [])
            return f"z.enum([{choices}])"
        case ResolvedTypeKind.CONCEPT:
            return _concept_schema(resolved_type, by_ref=by_ref, type_name_by_ref=type_name_by_ref)
        case ResolvedTypeKind.LIST:
            item = _zod_type(resolved_type.item, by_ref=by_ref, type_name_by_ref=type_name_by_ref) if resolved_type.item else "z.unknown()"
            return f"z.array({item})"
        case ResolvedTypeKind.DICT:
            value = _zod_type(resolved_type.value, by_ref=by_ref, type_name_by_ref=type_name_by_ref) if resolved_type.value else "z.unknown()"
            return f"z.record(z.string(), {value})"
        case ResolvedTypeKind.ANY:
            return "z.unknown()"


def _concept_schema(
    resolved_type: ResolvedType,
    *,
    by_ref: dict[str, ResolvedConcept],
    type_name_by_ref: dict[str, str],
) -> str:
    concept_ref = resolved_type.concept_ref
    if concept_ref is None:
        return "z.unknown()"
    concept = by_ref.get(concept_ref)
    if concept is not None:
        name = type_name_by_ref[concept.concept_ref]
        return f"z.lazy(() => {name}Schema)"
    return "z.unknown()"


def _emit_binder(concepts: list[ResolvedConcept], *, type_name_by_ref: dict[str, str]) -> EmittedFile:
    """Emit `binder.ts`: typed `parse<Name>` / `serialize<Name>` helpers over the `types.ts` schemas.

    Keys are wire-native (D10), so parse/serialize are a direct `Schema.parse` — no key remapping, and
    thus no risk of corrupting arbitrary keys inside a `z.record()` / `z.unknown()` value.
    """
    type_names = [type_name_by_ref[concept.concept_ref] for concept in concepts]
    if not type_names:
        # No pair to bind: the header alone is the canonical empty binder. The populated shape degenerates
        # into `import {  } from "./types";` (prettier rewrites the empty brace pair) above a trailing
        # blank-line run (prettier collapses it) — either reformat breaks the stamped body hash.
        return EmittedFile(filename=_BINDER_FILENAME, content=_binder_header())

    specifiers = [specifier for name in type_names for specifier in (f"{name}Schema", f"type {name}")]
    pairs = "\n\n".join(_binder_pair(name) for name in type_names)

    # Match prettier: one line while it fits, otherwise one specifier per line.
    single_line = f'import {{ {", ".join(specifiers)} }} from "./types";'
    if len(single_line) <= TS_PRINT_WIDTH:
        prelude = single_line
    else:
        import_lines = "\n".join(f"  {specifier}," for specifier in specifiers)
        prelude = f'import {{\n{import_lines}\n}} from "./types";'

    return EmittedFile(filename=_BINDER_FILENAME, content=f"{_binder_header()}{prelude}\n\n{pairs}\n")


def _binder_pair(type_name: str) -> str:
    """The `parse<Name>` / `serialize<Name>` pair for one concept type (wire-native, so `Schema.parse`)."""
    return (
        f"/** Parse a wire payload into a validated `{type_name}`. */\n"
        f"{_ts_signature(f'parse{type_name}', param='wire: unknown', returns=type_name)}\n"
        f"  return {type_name}Schema.parse(wire);\n"
        f"}}\n\n"
        f"/** Validate a `{type_name}` for the wire (keys are already wire-native). */\n"
        f"{_ts_signature(f'serialize{type_name}', param=f'value: {type_name}', returns=type_name)}\n"
        f"  return {type_name}Schema.parse(value);\n"
        f"}}"
    )


def _ts_signature(name: str, *, param: str, returns: str) -> str:
    """A `export function name(param): Returns {` header, wrapped the way prettier wraps it past the print width.

    A concept code long enough to push the signature over the width is perfectly valid MTHDS, and prettier
    breaks the parameter list onto its own line when it does not fit — a byte rewrite that breaks the stamp.
    """
    flat = f"export function {name}({param}): {returns} {{"
    if len(flat) <= TS_PRINT_WIDTH:
        return flat
    return f"export function {name}(\n  {param},\n): {returns} {{"


def _binder_header() -> str:
    return (
        "// ---------------------------------------------------------------------------\n"
        "// AUTOGENERATED by Pipelex codegen — DO NOT EDIT.\n"
        "//\n"
        "// Typed parse/serialize helpers over the pure `types.ts` schemas. Field keys are\n"
        "// wire-native (snake_case), so parse/serialize validate the wire payload directly.\n"
        "//\n"
        "// projection: types / ts-zod (binder)\n"
        "// ---------------------------------------------------------------------------\n"
    )


def _jsdoc(description: str, *, imprecise: str | None, indent: str = "") -> str:
    parts = _sanitize_jsdoc_text(description).split("\n") if description else []
    if imprecise:
        imprecise_lines = _sanitize_jsdoc_text(imprecise).split("\n")
        parts.append(f"@imprecise {imprecise_lines[0]}")
        parts.extend(imprecise_lines[1:])
    if not parts:
        return ""
    if len(parts) == 1 and imprecise is None:
        return f"{indent}/** {parts[0]} */\n"
    # `rstrip` rather than a plain f-string: a blank part (a paragraph break in the authored
    # description) would otherwise emit `" * "`, and prettier rewrites that to `" *"` under every
    # config — byte-changing the artifact and breaking its stamp. It covers a part carrying its own
    # trailing whitespace in the same stroke. The `*` is not whitespace, so the indent survives.
    body = "".join(f"{indent} * {part}".rstrip() + "\n" for part in parts)
    return f"{indent}/**\n{body}{indent} */\n"


def _sanitize_jsdoc_text(value: str) -> str:
    """Normalize line endings and neutralize comment terminators in authored JSDoc text."""
    normalized = value.replace("\r\n", "\n").replace("\r", "\n")
    return normalized.replace("*/", "* /")
