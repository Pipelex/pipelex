class TestStructureGeneratorClassDocstringEscaping:
    """A class description renders as a docstring that reads back as authored, whatever characters it holds."""

    @pytest.mark.parametrize(
        ("description", "with_field"),
        [
            pytest.param(f'"""\n{_RUN_STATEMENT}\n_ = """', False, id="triple-quotes-across-lines"),
            pytest.param(f'""";{_RUN_STATEMENT};"""{_PADDING}', False, id="triple-quotes-in-a-long-description"),
            pytest.param(f'""";{_RUN_STATEMENT};"""{_PADDING}', True, id="triple-quotes-in-a-long-description-with-a-field"),
            pytest.param(f"Both \"\"\" and ''' delimiters;{_RUN_STATEMENT};'''", False, id="both-triple-quote-styles"),
            pytest.param('Ends with a double quote: "quoted"', False, id="trailing-double-quote"),
            pytest.param("Ends with a single quote: 'quoted'", False, id="trailing-single-quote"),
            pytest.param("Ends with a backslash \\", False, id="trailing-backslash"),
            pytest.param("A Windows path C:\\new\\table and a lone \\ in the middle", False, id="backslashes-mid-text"),
            pytest.param("A bell \x07 and a NUL \x00 inside", False, id="control-character-and-nul"),
            pytest.param("Summary line.\n\nSecond paragraph with a list:\n  - first item\n  - second item", False, id="multi-line"),
            pytest.param(_LONG_DESCRIPTION, True, id="longer-than-a-line"),
            pytest.param("\n    Indented first line after a blank one\n  and a shallower line", False, id="blank-first-line-then-indented"),
        ],
    )
    def test_class_description_renders_verbatim_and_runs_no_statement(self, description: str, with_field: bool):
        """A description containing triple quotes, backslashes or control characters renders verbatim and runs no statement."""
        blueprint = (
            {"value": ConceptStructureBlueprint(type=ConceptStructureBlueprintFieldType.TEXT, description="A value", required=True)}
            if with_field
            else {}
        )

        _, generated_class = StructureGenerator().generate_from_structure_blueprint(
            class_name="Described", structure_blueprint=blueprint, description=description
        )

        assert STATEMENTS_RUN == []
        assert inspect.getdoc(generated_class) == normalized_docstring_text(description)

    def test_indented_body_after_a_blank_first_line_keeps_its_relative_indentation(self):
        """A description that opens on a blank line and indents its whole body reads back as `inspect.cleandoc` leaves it."""
        description = "\n  Intro:\n    - item one\n    - item two"

        _, generated_class = StructureGenerator().generate_from_structure_blueprint(
            class_name="Described", structure_blueprint={}, description=description
        )

        assert inspect.getdoc(generated_class) == "Intro:\n  - item one\n  - item two"
        assert generated_class.model_json_schema()["description"] == "Intro:\n  - item one\n  - item two"  # type: ignore[attr-defined]  # pyright: ignore[reportAttributeAccessIssue]

    def test_long_class_description_gains_no_line_break(self):
        """A one-line description longer than any line limit stays one line: no newline the author did not write."""
        _, generated_class = StructureGenerator().generate_from_structure_blueprint(
            class_name="Described", structure_blueprint={}, description=_LONG_DESCRIPTION
        )

        assert inspect.getdoc(generated_class) == _LONG_DESCRIPTION
        assert generated_class.model_json_schema()["description"] == _LONG_DESCRIPTION  # type: ignore[attr-defined]  # pyright: ignore[reportAttributeAccessIssue]


class TestStructureGeneratorModuleShapeCheck:
    """The generated module is checked for the shape the generator emits before it runs."""

    def test_module_of_the_generated_shape_is_accepted(self):
        """A module of the shape the generator emits passes the check and yields its class."""
        python_code = (
            f'{_MODULE_HEAD}class Shaped(StructuredContent):\n    """A shaped class"""\n\n    value: str = Field(..., description="A value")\n'
        )

        the_class = StructureGenerator().validate_generated_code(python_code=python_code, expected_class_name="Shaped")

        assert the_class.__name__ == "Shaped"

    @pytest.mark.parametrize(
        "python_code",
        [
            pytest.param(f"from pipelex.core.stuffs.structured_content import StructuredContent\n\n\n{_SHAPED_CLASS}", id="no-header-docstring"),
            pytest.param(f"{_RUN_STATEMENT}\n\n\n{_SHAPED_CLASS}", id="statement-in-place-of-the-header"),
            pytest.param('"""A header and nothing else."""\n', id="header-without-a-class"),
        ],
    )
    def test_module_without_its_header_and_class_is_refused_before_it_runs(self, python_code: str):
        """A module that does not open with its header docstring followed by its class is refused, and none of it runs."""
        with pytest.raises(ConceptStructureValidationError, match="does not open with its header docstring followed by its class"):
            StructureGenerator().validate_generated_code(python_code=python_code, expected_class_name="Shaped")

        assert STATEMENTS_RUN == []

    @pytest.mark.parametrize(
        "python_code",
        [
            pytest.param(
                f'{_MODULE_HEAD}{_RUN_STATEMENT}\n\n\nclass Shaped(StructuredContent):\n    """A shaped class"""\n',
                id="statement-before-the-class",
            ),
            pytest.param(
                f'{_MODULE_HEAD}class Shaped(StructuredContent):\n    """A shaped class"""\n\n\n{_RUN_STATEMENT}\n',
                id="statement-after-the-class",
            ),
            pytest.param(
                f'{_MODULE_HEAD}_ = {_RUN_STATEMENT}\n\n\nclass Shaped(StructuredContent):\n    """A shaped class"""\n',
                id="assignment-before-the-class",
            ),
            pytest.param(f'{_MODULE_HEAD}class Other(StructuredContent):\n    """A shaped class"""\n', id="class-of-another-name"),
            pytest.param(
                f'{_MODULE_HEAD}class Shaped(StructuredContent):\n    """A shaped class"""\n\n\nclass Shaped(StructuredContent):\n    """Again"""\n',
                id="two-classes",
            ),
            pytest.param(f'{_MODULE_HEAD}def Shaped():\n    """A shaped function"""\n', id="function-in-place-of-the-class"),
            pytest.param(
                f'{_MODULE_HEAD}@(lambda cls: [{_RUN_STATEMENT}, cls][1])\nclass Shaped(StructuredContent):\n    """A shaped class"""\n',
                id="decorated-class",
            ),
            pytest.param(
                f'{_MODULE_HEAD}class Shaped(StructuredContent, metaclass=type):\n    """A shaped class"""\n',
                id="class-keyword",
            ),
            pytest.param(
                f'{_MODULE_HEAD}class Shaped(StructuredContent):\n    """A shaped class"""\n\n\n"""A late string"""\n',
                id="string-after-the-class",
            ),
        ],
    )
    def test_module_of_another_shape_is_refused_before_it_runs(self, python_code: str):
        """A module holding a top-level statement the generator never emits is refused, and none of it runs."""
        with pytest.raises(ConceptStructureValidationError):
            StructureGenerator().validate_generated_code(python_code=python_code, expected_class_name="Shaped")

        assert STATEMENTS_RUN == []

    @pytest.mark.parametrize(
        "class_body",
        [
            pytest.param(f'    """A shaped class"""\n\n    {_RUN_STATEMENT}\n', id="expression-statement"),
            pytest.param(f'    """A shaped class"""\n\n    value = {_RUN_STATEMENT}\n', id="plain-assignment"),
            pytest.param(f'    """A shaped class"""\n\n    def value(self):\n        {_RUN_STATEMENT}\n', id="method"),
            pytest.param(f'    """A shaped class"""\n\n    if True:\n        {_RUN_STATEMENT}\n', id="if-statement"),
            pytest.param('    """A shaped class"""\n\n    self.value: str = Field(..., description="A value")\n', id="attribute-target"),
            pytest.param('    value: str = Field(..., description="A value")\n    """A late string"""\n', id="string-after-a-field"),
            pytest.param('    """A shaped class"""\n    """A second string"""\n', id="two-strings"),
        ],
    )
    def test_class_body_of_another_shape_is_refused_before_it_runs(self, class_body: str):
        """A class body holding anything but its docstring and annotated fields is refused, and none of it runs."""
        python_code = f"{_MODULE_HEAD}class Shaped(StructuredContent):\n{class_body}"

        with pytest.raises(ConceptStructureValidationError):
            StructureGenerator().validate_generated_code(python_code=python_code, expected_class_name="Shaped")

        assert STATEMENTS_RUN == []
