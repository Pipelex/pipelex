from pathlib import Path

import pytest
from mthds.method_tree.lister import list_method_tree

from pipelex.core.method_trees.exceptions import TreePythonError
from pipelex.core.method_trees.tree_files import Base64FileEntry, encode_tree_file, read_call_files, tree_file_bytes, write_call_files
from pipelex.libraries.pipe_func_call_files import travels_with_call

_PNG_BYTES = b"\x89PNG\r\n\x1a\n\x00\x00"


class TestTreeFiles:
    @pytest.mark.parametrize(
        ("data", "is_text"),
        [pytest.param(b"VAT_RATE = 0.2\n", True, id="utf-8-text"), pytest.param(_PNG_BYTES, False, id="binary")],
    )
    def test_a_file_travels_as_its_text_or_in_base64_and_round_trips(self, data: bytes, is_text: bool) -> None:
        entry = encode_tree_file(data=data)

        assert isinstance(entry, str) is is_text
        assert isinstance(entry, Base64FileEntry) is not is_text
        assert tree_file_bytes(entry=entry) == data

    def test_a_call_receives_every_file_of_the_tree_but_its_bundles_and_what_the_tree_excludes(self, tmp_path: Path) -> None:
        method_dir = tmp_path / "invoicing"
        (method_dir / "funcs").mkdir(parents=True)
        (method_dir / "invoicing.mthds").write_text('domain = "invoicing"\n', encoding="utf-8")
        (method_dir / "funcs" / "totals.py").write_text("TOTAL = 1\n", encoding="utf-8")
        (method_dir / "logo.png").write_bytes(_PNG_BYTES)
        (method_dir / ".gitignore").write_text("scratch.py\n", encoding="utf-8")
        (method_dir / "scratch.py").write_text("NOT_SHIPPED = True\n", encoding="utf-8")
        (method_dir / "structures.py").write_text(
            "# Generated by Pipelex\nfrom pipelex.core.stuffs.structured_content import StructuredContent\n", encoding="utf-8"
        )

        files = read_call_files(tree=list_method_tree(method_dir))

        assert sorted(files) == ["funcs/totals.py", "logo.png", "structures.py"]
        assert files["funcs/totals.py"] == "TOTAL = 1\n"
        assert files["logo.png"] == Base64FileEntry.make_from_bytes(_PNG_BYTES)

    def test_a_filter_keeps_a_file_out_of_the_call(self, tmp_path: Path) -> None:
        method_dir = tmp_path / "filtered"
        method_dir.mkdir()
        (method_dir / "filtered.mthds").write_text('domain = "filtered"\n', encoding="utf-8")
        (method_dir / "helpers.py").write_text("X = 1\n", encoding="utf-8")

        def _keeps(*, tree_path: str, data: bytes) -> bool:
            return tree_path != "helpers.py" and bool(data)

        files = read_call_files(tree=list_method_tree(method_dir), keeps=_keeps)

        assert files == {}
        assert travels_with_call(tree_path="logo.png", data=_PNG_BYTES)
        assert travels_with_call(tree_path="helpers.py", data=b"X = 1\n")

    def test_the_files_a_call_received_are_written_at_their_tree_paths(self, tmp_path: Path) -> None:
        write_call_files(files={"funcs/totals.py": "TOTAL = 1\n", "logo.png": Base64FileEntry.make_from_bytes(_PNG_BYTES)}, destination=tmp_path)

        assert (tmp_path / "funcs" / "totals.py").read_text(encoding="utf-8") == "TOTAL = 1\n"
        assert (tmp_path / "logo.png").read_bytes() == _PNG_BYTES

    @pytest.mark.parametrize("tree_path", ["../escape.py", "/etc/escape.py", "funcs//totals.py"], ids=["climbing", "absolute", "empty-segment"])
    def test_a_key_that_is_not_a_tree_path_is_refused_before_anything_is_written(self, tmp_path: Path, tree_path: str) -> None:
        destination = tmp_path / "call"
        destination.mkdir()

        with pytest.raises(TreePythonError, match="which is not a tree path"):
            write_call_files(files={tree_path: "X = 1\n"}, destination=destination)

        assert not (tmp_path / "escape.py").exists()
