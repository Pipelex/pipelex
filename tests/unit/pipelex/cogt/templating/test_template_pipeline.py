"""Integration tests for template preprocessing and variable detection working together.

These tests verify the complete pipeline: preprocess_template converts custom syntax (@, $, @?)
to Jinja2 syntax, then detect_jinja2_required_variables extracts the required variables.
"""

from typing import ClassVar

import pytest

from pipelex.cogt.templating.template_category import TemplateCategory
from pipelex.cogt.templating.template_errors import TemplateSigilSyntaxError
from pipelex.cogt.templating.template_preprocessor import preprocess_template
from pipelex.tools.jinja2.jinja2_required_variables import detect_jinja2_required_variables


