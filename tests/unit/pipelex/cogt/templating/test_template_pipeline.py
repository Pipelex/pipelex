class TestTemplatePipelineIntegration:
    """Tests for the complete template preprocessing and variable detection pipeline."""

    @pytest.mark.parametrize(
        ("topic", "raw_template", "expected_jinja2", "expected_variables"),
        TestData.AT_VARIABLE_PIPELINE,
    )
    def test_at_variable_pipeline(
        self,
        topic: str,
        raw_template: str,
        expected_jinja2: str,
        expected_variables: set[str],
    ):
        """Test @ variable pattern through the complete pipeline."""
        # Step 1: Preprocess
        processed = preprocess_template(raw_template)
        assert processed == expected_jinja2, f"Preprocessing failed for topic: {topic}"

        # Step 2: Detect variables
        variables = detect_jinja2_required_variables(
            template_category=TemplateCategory.LLM_PROMPT,
            template_source=processed,
        )
        assert variables == expected_variables, f"Variable detection failed for topic: {topic}"

    @pytest.mark.parametrize(
        ("topic", "raw_template"),
        TestData.AT_VARIABLE_PIPELINE_ERRORS,
    )
    def test_at_variable_pipeline_raises_when_inline(self, topic: str, raw_template: str):
        """Inline @-sigils violate the strict line-bounded rule and raise."""
        with pytest.raises(TemplateSigilSyntaxError) as exc_info:
            preprocess_template(raw_template)
        assert "line " in str(exc_info.value), f"Missing line number in error for topic: {topic}"

